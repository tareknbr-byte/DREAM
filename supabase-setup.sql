-- Glow Club product table and secure access policies for Supabase
-- Run this in Supabase Dashboard -> SQL Editor -> New query.
-- Before using the site, create the admin user in Authentication -> Users.
-- Replace YOUR_ADMIN_AUTH_USER_UUID below with that user's exact UUID.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  category text not null default 'Other' check (category in ('Lips','Face','Eyes','Skin','Other')),
  price numeric(12,2) not null default 0 check (price >= 0),
  color text not null default '#FF6FA5',
  stock boolean not null default true,
  image_url text,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;

drop policy if exists "Anyone can view products" on public.products;
create policy "Anyone can view products"
on public.products for select
to anon, authenticated
using (true);

-- Replace the UUID below with your admin user's UUID.
drop policy if exists "Only configured admin can insert products" on public.products;
create policy "Only configured admin can insert products"
on public.products for insert
to authenticated
with check (auth.uid() = 'YOUR_ADMIN_AUTH_USER_UUID'::uuid);

drop policy if exists "Only configured admin can update products" on public.products;
create policy "Only configured admin can update products"
on public.products for update
to authenticated
using (auth.uid() = 'YOUR_ADMIN_AUTH_USER_UUID'::uuid)
with check (auth.uid() = 'YOUR_ADMIN_AUTH_USER_UUID'::uuid);

drop policy if exists "Only configured admin can delete products" on public.products;
create policy "Only configured admin can delete products"
on public.products for delete
to authenticated
using (auth.uid() = 'YOUR_ADMIN_AUTH_USER_UUID'::uuid);

